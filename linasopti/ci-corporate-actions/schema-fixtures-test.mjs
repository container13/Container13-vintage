function strict(e){const c=classifyEvent('forward_splits',e);if(c.status!=='validated')return c.status;return e.id&&e.cusip?'validated':'incomplete';}
assert.equal(strict(event),'validated');
assert.equal(strict(missingId),'incomplete');
assert.equal(strict(missingCusip),'incomplete');
assert.equal(classifyEvent('forward_splits',{...event,new_rate:0}).status,'invalid');
assert.equal(classifyEvent('forward_splits',{...event,ex_date:null}).status,'incomplete');
assert.equal(classifyEventV4('forward_splits',event).status,'validated');
assert.deepEqual(classifyEventV4('forward_splits',missingId),{status:'incomplete',reason:'MISSING_ID'});
assert.deepEqual(classifyEventV4('forward_splits',missingCusip),{status:'incomplete',reason:'MISSING_CUSIP'});
assert.equal(classifyEventV4('forward_splits',{...event,new_rate:0}).status,'invalid');
assert.equal(classifyEventV4('forward_splits',{...event,ex_date:null}).status,'incomplete');
const dividend={id:'dividend-1',symbol:'AAPL',process_date:'2020-08-31',ex_date:'2020-08-31',rate:0.25};
